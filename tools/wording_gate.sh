#!/usr/bin/env bash
# The wording gate (#33; CLAUDE.md rule 13, NORTH-STAR.md §2's no-list, the lane brief of 2026-10-06): greps the
# PUBLIC PAGES for the forms that may not leave this repository and prints every hit with its file and line;
# exit 1 on any hit, exit 0 when clean. Run: tools/wording_gate.sh [--list]   (--list prints the page set and exits).
#
# THE PAGES: README.md, NORTH-STAR.md, docs/*.md (the top level: docs/records/ and docs/audit/ are history and are
# never scanned) and spec/*.md (the generated index pages; a hit there is fixed in the Lean docstring it came from
# and regenerated by `make spec`). One top-level page is skipped BY NAME: docs/BLOCKS-ARCHIVE.md, the append-only
# archive of past sittings' blocks, which its own header forbids rewriting and whose public form the export of #46
# decides; WORDING_GATE_ALL=1 scans it too.
#
# THE FORMS (the words are named here by description and written in the code with a character class, so this file
# carries none of them; tools/export_gate.py's WORDING list is written the same way):
#   priority-word  the ordinal word (any case) outside the allowed phrases of tools/wording_allow.txt. Allowed: the word
#                as a position in a sequence the reference or the spec defines (bytes, inputs, outputs, list elements,
#                checks, steps) and a cut, round, half or run of this repository's own artifacts; NOT allowed: the word
#                ranking this work, a report, a theorem set or a property set against the world, or a dated "for the
#                ... time". A new ordinal use is added to that list as its exact phrase, a new claim is reworded. The
#                match is line by line: an ordinal phrase wrapped across two lines is a hit until its source re-wraps it.
#   claim        the novelty adjectives and the "-ever" form of the ordinal (whole words, any case): no allowlist.
#   conformance-claim  the unqualified word for matching a reference without a run, any case; the allowed phrases are
#                the rule's own statement and its quoted form.
#   licence-adjective  the licence adjective the owner retired, any case; the allowed phrases are the ruling's own
#                statement and its quoted word (the owner's license ruling of 2026-10-05: no public sentence calls the
#                spec by that adjective).
#   dash         the long dash (U+2014) or its HTML entity.
#   private      the private programs' names: the VOCAB line of tools/host_private.sh (the owner's host file, which
#                tools/mechanism_check.sh sources), read at run time so the two lists never drift, plus the gate's own
#                patterns in tools/wording_patterns.txt (a data file in tools/export_pointers.txt's form); both are
#                withheld from the public edition by tools/export_withheld.txt, so this script carries no name; matched
#                as whole words with an optional plural `s`.
# OUTPUT: one line per hit, `<form>\t<file>:<line>: <text>`, then a summary line; the record of a run is the caller's
# (docs/records/<stamp>-writeup-33.md carries the run of 2026-10-06 before and after the fixes).
set -uo pipefail
# Optional positional page paths restrict a run; without them the usual pages apply.
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT" || exit 2

pages=()
for f in README.md NORTH-STAR.md docs/*.md spec/*.md; do
  [ -f "$f" ] || continue
  if [ "$f" = "docs/BLOCKS-ARCHIVE.md" ] && [ -z "${WORDING_GATE_ALL:-}" ]; then continue; fi
  pages+=("$f")
done
if [ "${1:-}" = "--list" ]; then printf '%s\n' "${pages[@]}"; exit 0; fi
if [ "$#" -gt 0 ]; then
  pages=()
  for f in "$@"; do
    if [ ! -f "$f" ]; then echo "wording gate: page $f absent; stop" >&2; exit 2; fi
    pages+=("$f")
  done
fi

# The allowed phrases: tools/wording_allow.txt, the one list tools/export_gate.py reads too (exact phrases, matched
# case-insensitively, one per line; CLAUDE.md rule 13: the exact phrases found, never a class of them). A phrase is
# stripped from a line before the word is looked for, so a hit inside an allowed phrase is not a hit.
ALLOW_FILE="$ROOT/tools/wording_allow.txt"
if [ ! -f "$ALLOW_FILE" ]; then echo "wording gate: $ALLOW_FILE absent; stop" >&2; exit 2; fi
ALLOWED="$(grep -v -E '^[[:space:]]*(#|$)' "$ALLOW_FILE" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//' | tr '[:upper:]' '[:lower:]')"
# the gated words, written with a character class so this file carries none of them
W_PRIORITY='\bfirs[t]\b'; W_CLAIM='\b(nove[l]|unprecedente[d]|firs[t]-ever)\b'; W_CONFORM='conforman[t]'; W_LICENCE='permissiv[e]'
W_DASH="$(printf '\342\200\224')|&mdash;"

VOCAB="$(sed -n "s/^VOCAB='\(.*\)'$/\1/p" "$ROOT/tools/host_private.sh" 2>/dev/null | head -1)"
if [ -z "$VOCAB" ]; then echo "wording gate: tools/host_private.sh carries no VOCAB line; stop" >&2; exit 2; fi
# the gate's own list, read from its data file: one extended regex per line, `#` a comment, `## <group>` a group
PATTERNS="$ROOT/tools/wording_patterns.txt"
if [ ! -f "$PATTERNS" ]; then echo "wording gate: $PATTERNS absent; stop" >&2; exit 2; fi
OWN="$(grep -v -E '^[[:space:]]*(#|$)' "$PATTERNS" | paste -sd'|' -)"
if [ -z "$OWN" ]; then echo "wording gate: $PATTERNS carries no pattern; stop" >&2; exit 2; fi
PRIVATE="\\b(${VOCAB}|${OWN})s?\\b"

hits=0
hit() { hits=$((hits + 1)); printf '%s\t%s:%s: %s\n' "$1" "$2" "$3" "$4"; }

# strips every allowed phrase from a line and says whether the word survives
survives() {   # $1 the line, $2 the allowlist (newline-separated, lower case), $3 the word regex (grep -E, case-insensitive)
  local line p
  line="$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')"
  while IFS= read -r p; do
    [ -n "$p" ] || continue
    line="${line//"$p"/ }"
  done <<EOF
$2
EOF
  printf '%s' "$line" | grep -qiE "$3"
}

for f in "${pages[@]}"; do
  # the priority word
  while IFS= read -r l; do
    n="${l%%:*}"; t="${l#*:}"
    if survives "$t" "$ALLOWED" "$W_PRIORITY"; then hit priority-word "$f" "$n" "$t"; fi
  done < <(grep -n -i -E "$W_PRIORITY" "$f" || true)
  # the other claim words
  while IFS= read -r l; do
    n="${l%%:*}"; t="${l#*:}"; hit claim "$f" "$n" "$t"
  done < <(grep -n -i -E "$W_CLAIM" "$f" || true)
  # the word for matching a reference without a run
  while IFS= read -r l; do
    n="${l%%:*}"; t="${l#*:}"
    if survives "$t" "$ALLOWED" "$W_CONFORM"; then hit conformance-claim "$f" "$n" "$t"; fi
  done < <(grep -n -i -E "$W_CONFORM" "$f" || true)
  # the licence adjective the owner retired
  while IFS= read -r l; do
    n="${l%%:*}"; t="${l#*:}"
    if survives "$t" "$ALLOWED" "$W_LICENCE"; then hit licence-adjective "$f" "$n" "$t"; fi
  done < <(grep -n -i -E "$W_LICENCE" "$f" || true)
  # the long dash
  while IFS= read -r l; do
    n="${l%%:*}"; t="${l#*:}"; hit dash "$f" "$n" "$t"
  done < <(grep -n -E "$W_DASH" "$f" || true)
  # the private programs' names
  while IFS= read -r l; do
    n="${l%%:*}"; t="${l#*:}"; hit private "$f" "$n" "$t"
  done < <(grep -n -E "$PRIVATE" "$f" || true)
done

if [ "$hits" -eq 0 ]; then
  echo "wording gate: CLEAN (${#pages[@]} pages; the forms: priority-word, claim, conformance-claim, licence-adjective, dash, private)"
  exit 0
fi
echo "wording gate: $hits hit(s) over ${#pages[@]} pages (the forms: priority-word, claim, conformance-claim, licence-adjective, dash, private); exit 1" >&2
exit 1
