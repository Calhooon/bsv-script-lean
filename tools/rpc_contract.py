def verify(c):
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from check_pins import clone_path, pins_block  # docs/PROVENANCE.md §1a, the pins leg's own reader
    p = pins_block()
    repos = {"src/": ("reference", clone_path(p.get("reference.clone", "")), p.get("reference.commit")),
             "services/": ("teranode", clone_path(p.get("teranode.clone", "")), p.get("teranode.commit"))}
    cache, bad, checked, skipped = {}, [], 0, {}
    cites = []

    def walk(v, msg=None):
        if isinstance(v, dict):
            for k, x in v.items():
                if k in ("cite", "source", "registration", "registered", "parser", "map", "handler", "http_status", "error_object", "dispatch", "named_arguments",
                         "safe_mode_gate", "safe_mode_warning") and isinstance(x, str):
                    cites.append((x, v.get("message") if k == "cite" else None))
                elif k == "helpers" or (k == "source" and isinstance(x, list)):
                    cites.extend((y, None) for y in x)
                else:
                    walk(x)
        elif isinstance(v, list):
            for x in v:
                walk(x)
    walk(c)
    for cite, message in cites:
        m = re.fullmatch(r"((?:src|services)/[^:]+):(\d+)(?:-(\d+))?", cite)
        if not m:
            bad.append(f"{cite}: not a citation")
            continue
        path, a, b = m.group(1), int(m.group(2)), int(m.group(3) or m.group(2))
        repo, clone, commit = next(v for k, v in repos.items() if path.startswith(k))
        if not os.path.isdir(clone):
            skipped[repo] = skipped.get(repo, 0) + 1
            continue
        if (commit, path) not in cache:
            r = subprocess.run(["git", "-C", clone, "show", f"{commit}:{path}"], capture_output=True)
            cache[(commit, path)] = r.stdout.decode("utf-8", "replace").split("\n") if r.returncode == 0 else None
        text = cache[(commit, path)]
        checked += 1
        if text is None or not 1 <= a <= b <= len(text):
            bad.append(f"{cite}: outside {path} at {repo} {commit[:12]}")
        elif message and "<" not in message and not any(head in text[i - 1] or head.replace('"', '\\"') in text[i - 1]
                                                       for head in [message.split(" / ")[0].replace("\\n", "")[:18]]
                                                       for i in range(max(1, a - 1), min(len(text), b + 1) + 1)):
            bad.append(f"{cite}: the message {message[:40]!r} is not on the cited line")
    for repo in sorted(skipped):
        print(f"rpc_contract verify: {repo} clone absent: SKIPPED BY NAME")
    return checked, bad, skipped


