SCENARIOS = os.path.join(ROOT, "harness", "src", "scenarios")
PRIMS = {"i64": "i64", "u64": "u64", "f64": "f64", "bool": "bool", "string": "String", "null": "()", "json": "Value"}
KEYWORDS = {"type", "ref", "match", "fn", "use", "mod", "move", "self", "struct", "enum", "impl", "loop", "where"}


def load():
    with open(CONTRACT, encoding="utf-8") as f:
        return json.load(f)


# ------------------------------------------------------------------ names
def snake(name):
    s = re.sub(r"[^0-9A-Za-z]+", "_", name)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s).lower().strip("_")
    return s + "_" if s in KEYWORDS else s


# ------------------------------------------------------------------ Rust
def rtype(t, boxed=False):
    if isinstance(t, str):
        return PRIMS[t]
    if "array" in t:
        return f"Vec<{rtype(t['array'])}>"
    if "map" in t:
        return f"BTreeMap<String, {rtype(t['map'])}>"
    if "option" in t:
        return f"Option<{rtype(t['option'])}>"
    if "nullable" in t:
        return f"Option<{rtype(t['nullable'])}>"
    return f"Box<{t['ref']}>" if boxed else t["ref"]


def arg_rust(a):
    base = {"i64": "i64", "u64": "u64", "f64": "f64", "bool": "bool", "string": "&str"}.get(a["type"] if isinstance(a["type"], str) else "", "Value")
    return base if a["required"] else f"Option<{base}>"


def arg_reader(a, i):
    kind = a["type"] if isinstance(a["type"], str) and a["type"] in ("i64", "u64", "f64", "bool", "string") else "json"
    reader = {"i64": "i64", "u64": "u64", "f64": "f64", "bool": "bool", "string": "str", "json": "value"}[kind]
    return f"{'arg' if a['required'] else 'opt'}_{reader}(params, {i})?"


def doc(text):
    return f"/// {text}"


def rust(c):
    out = []
    w = out.append
    w("// GENERATED by tools/rpc_contract.py from corpus/rpc/contract.json (#85, lane rpc-85, 2026-10-15); do not edit by hand:")
    w("// change the contract and run `python3 tools/rpc_contract.py` (`--check` is the staleness test).")
    w("//! The #66 runner's typed RPC interface: one method per handler of the contract, each cited at the reference pin")
    w(f"//! (bitcoin-sv {c['reference']['tag']} at {c['reference']['commit']}) [SRC]; the types are [D]. Not yet called by the")
    w("//! runner: harness/tests/rpc_contract.rs replays the probe's recorded node replies through it.")
    w("use serde::{Deserialize, Serialize};")
    w("use serde_json::{json, Value};")
    w("use std::collections::BTreeMap;")
    w("")
    w("pub type Result<T> = std::result::Result<T, String>;")
    w("")
    w("/// The positional array: trailing absent arguments are dropped; an absent one before a present one is refused,")
    w("/// since every handler reads its arguments by position (src/rpc/server.cpp transformNamedArguments for named ones).")
    w("pub fn positional(args: Vec<Option<Value>>) -> Result<Value> {")
    w("    let used = args.iter().rposition(Option::is_some).map_or(0, |i| i + 1);")
    w("    let mut params = Vec::with_capacity(used);")
    w("    for (i, arg) in args.into_iter().take(used).enumerate() {")
    w("        params.push(arg.ok_or_else(|| format!(\"argument {i} absent before a present one\"))?);")
    w("    }")
    w("    Ok(Value::Array(params))")
    w("}")
    w("")
    w("/// A reply outside the contract's type is an error naming the handler.")
    w("pub fn decode<T: serde::de::DeserializeOwned>(method: &str, reply: Value) -> Result<T> {")
    w("    serde_json::from_value(reply).map_err(|e| format!(\"{method}: reply outside the contract: {e}\"))")
    w("}")
    w("")
    for name, t in sorted(c["types"].items()):
        w(doc(f"[D] `{name}`: {t['cite']} [SRC]."))
        if t["kind"] == "either":
            w("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]")
            w("#[serde(untagged)]")
            w(f"pub enum {name} {{")
            for v in t["variants"]:
                if v.get("note"):
                    w(f"    {doc(v['note'])}")
                w(f"    {v['name']}({rtype(v['type'], boxed=True)}),")
            w("}")
        else:
            w("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]")
            w(f"pub struct {name} {{")
            for f in t["fields"]:
                if "flatten" in f:
                    w("    " + doc(f"the fields of {f['flatten']}: {f['cite']}"))
                    w("    #[serde(flatten)]")
                    w(f"    pub {snake(f['flatten'])}: {f['flatten']},")
                    continue
                w(f"    {doc(f['cite'] + (': ' + f['note'] if f.get('note') else ''))}")
                attrs = []
                if snake(f["name"]) != f["name"]:
                    attrs.append(f'rename = "{f["name"]}"')
                if isinstance(f["type"], dict) and "option" in f["type"]:
                    attrs.append('default, skip_serializing_if = "Option::is_none"')
                elif isinstance(f["type"], dict) and "nullable" in f["type"]:
                    attrs.append("default")
                if attrs:
                    w(f"    #[serde({', '.join(attrs)})]")
                w(f"    pub {snake(f['name'])}: {rtype(f['type'])},")
            w("}")
        w("")
    w("/// The contract's handlers. `call_raw` is the transport: the node's `result`, or its error object as text.")
    w("pub trait RpcContract {")
    w("    fn call_raw(&mut self, method: &str, params: Value) -> Result<Value>;")
    for h in c["handlers"]:
        w("")
        w(f"    /// `{h['method']}` [SRC] {h['source']}, registered {h['registration']} (okSafeMode {str(h['ok_safe_mode']).lower()}); {h['build']} build.")
        sig = ", ".join(["&mut self"] + [f"{snake(a['name'])}: {arg_rust(a)}" for a in h["args"]])
        w(f"    fn {snake(h['method'])}({sig}) -> Result<{rtype(h['result'])}> {{")
        items = []
        for a in h["args"]:
            v = snake(a["name"])
            items.append(f"Some(json!({v}))" if a["required"] else f"{v}.map(|v| json!(v))")
        w(f"        let params = positional(vec![{', '.join(items)}])?;")
        w(f"        decode(\"{h['method']}\", self.call_raw(\"{h['method']}\", params)?)")
        w("    }")
    w("}")
    w("")
    used = {arg_reader(a, i).split("(")[0] for h in c["handlers"] for i, a in enumerate(h["args"])}
    readers = {
        "i64": ("i64", "params[i].as_i64().ok_or_else(|| format!(\"argument {i}: not i64\"))"),
        "u64": ("u64", "params[i].as_u64().ok_or_else(|| format!(\"argument {i}: not u64\"))"),
        "f64": ("f64", "params[i].as_f64().ok_or_else(|| format!(\"argument {i}: not f64\"))"),
        "bool": ("bool", "params[i].as_bool().ok_or_else(|| format!(\"argument {i}: not bool\"))"),
        "str": ("&str", "params[i].as_str().ok_or_else(|| format!(\"argument {i}: not a string\"))"),
        "value": ("Value", "params.get(i).cloned().ok_or_else(|| format!(\"argument {i}: absent\"))"),
    }
    for kind, (rt, body) in readers.items():
        if f"arg_{kind}" in used or f"opt_{kind}" in used:
            w(f"fn arg_{kind}(params: &Value, i: usize) -> Result<{rt}> {{")
            w(f"    {body}")
            w("}")
        if f"opt_{kind}" in used:
            w(f"fn opt_{kind}(params: &Value, i: usize) -> Result<Option<{rt}>> {{")
            w(f"    params.get(i).map(|_| arg_{kind}(params, i)).transpose()")
            w("}")
    w("")
    w("/// One handler called through its typed method from positional JSON arguments; the typed result re-serialized.")
    w("pub fn call_typed(node: &mut impl RpcContract, method: &str, params: &Value) -> Result<Value> {")
    w("    let typed = match method {")
    for h in c["handlers"]:
        args = ", ".join(arg_reader(a, i) for i, a in enumerate(h["args"]))
        w(f"        \"{h['method']}\" => serde_json::to_value(node.{snake(h['method'])}({args})?),")
    w("        _ => return Err(format!(\"{method}: not in the contract\")),")
    w("    };")
    w("    typed.map_err(|e| format!(\"{method}: {e}\"))")
    w("}")
    w("")
    w("/// One row per handler: its source and registration at the pin, okSafeMode, the build that carries it, the error")
    w("/// codes the contract lists for it (the envelope's generic codes apart) and the second oracle's class.")
    w("pub struct HandlerRow {")
    for f, t in (("method", "&'static str"), ("source", "&'static str"), ("registration", "&'static str"), ("ok_safe_mode", "bool"),
                 ("build", "&'static str"), ("errors", "&'static [i64]"), ("second_oracle", "&'static str")):
        w(f"    pub {f}: {t},")
    w("}")
    w("")
    w(f"pub const HANDLERS: [HandlerRow; {len(c['handlers'])}] = [")
    for h in c["handlers"]:
        codes = sorted({e["code"] for e in h["errors"]})
        w(f"    HandlerRow {{ method: \"{h['method']}\", source: \"{h['source']}\", registration: \"{h['registration']}\", "
          f"ok_safe_mode: {str(h['ok_safe_mode']).lower()}, build: \"{h['build']}\", errors: &[{', '.join(str(x) for x in codes)}], "
          f"second_oracle: \"{h['teranode']['class']}\" }},")
    w("];")
    text = "\n".join(out) + "\n"
    r = subprocess.run(["rustfmt", "--edition", "2021", "--emit", "stdout", "--config-path", os.path.join(ROOT, "harness", "rustfmt.toml")],
                       input=text, capture_output=True, text=True, cwd=os.path.join(ROOT, "harness"))
    if r.returncode != 0:
        sys.exit(f"rpc_contract: rustfmt refused the generated file: {r.stderr[:2000]}")
    return r.stdout


# ------------------------------------------------------------------ the page
def tname(t):
    if isinstance(t, str):
        return t
    for k in ("array", "map", "option", "nullable"):
        if k in t:
            return f"{k} of {tname(t[k])}" if k != "option" else f"{tname(t[k])}, may be absent"
    return t["ref"]


def cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def quoted(message):
    """A node message on the page: the contract keeps it literal; the page elides the ordinal word the wording gate
    holds (tools/wording_gate.sh, CLAUDE.md rule 13), marked [...]."""
    return cell(re.sub(r"\bfirs[t]\b", "[...]", message, flags=re.I))


def runner_tables():
    rows = []
    pat = re.compile(r'^\s*"([A-Za-z0-9]+)" => "((?:src|services)/[^"]+:\d+(?:-\d+)?)"')
    for name in sorted(os.listdir(SCENARIOS)):
        if not name.endswith(".rs") or name == "rpc_contract.rs":
            continue
        with open(os.path.join(SCENARIOS, name), encoding="utf-8") as f:
            for i, line in enumerate(f, 1):
                m = pat.match(line)
                if m:
                    rows.append((m.group(1), name, i, m.group(2)))
    return rows


def witnessed(c, record):
    out = {}
    for call in record:
        if "method" not in call:
            continue
        reply = call.get("reply") or {}
        err = reply.get("error") if isinstance(reply, dict) else None
        key = "ok" if isinstance(reply, dict) and "result" in reply and err is None else (str(err.get("code")) if isinstance(err, dict) else "raw")
        out.setdefault(call["method"], set()).add(key)
    return out


