        codes = ", ".join(str(x) for x in sorted({e["code"] for e in h["errors"]})) or "generic only"
        wit = ", ".join(sorted(seen.get(h["method"], set()))) or "not called"
        lines.append(f"| `{h['method']}` | `{h['source']}` | `{h['registration']}` ({str(h['ok_safe_mode']).lower()}) | {cell(args)} | {cell(tname(h['result']))} | "
                     f"{codes} | {h['teranode']['class']} | {wit} |")
