#!/usr/bin/env python3
"""tools/rpc_contract.py: the RPC observation contract's generator and checker (#85; S3's file, written 2026-10-15 by lane rpc-85).

THE SOURCE. corpus/rpc/contract.json: every handler the #66 runner calls (the five handler tables of
harness/src/scenarios/ and the second oracle's three calls), its arguments, result type, error codes, the behaviors under
safe mode, pruning and mock time, each cited at the reference pin (bitcoin-sv v1.2.3) and its counterpart at Teranode's
pin, from docs/PROVENANCE.md §1a. The types are a small language: i64, u64, f64, bool, string, null, json, {array: T},
{map: T}, {option: T} (a field that may be absent), {nullable: T} (present, may be null), {ref: Name}.

WHAT IT WRITES. harness/src/scenarios/rpc_contract.rs, the runner's typed interface: one result type per shape, the
trait `RpcContract` with one method per handler over a single transport method `call_raw`, a typed dispatcher
`call_typed` (JSON arguments in, the typed result re-serialized out) and the table `HANDLERS`. The file is formatted by
the harness's pinned rustfmt (harness/rust-toolchain.toml, harness/rustfmt.toml), so the fmt leg reads it as written.
The runner does not call it yet (the wiring is a later lane); harness/tests/rpc_contract.rs compiles it and replays the
probe's recorded replies through it. It also writes the generated sections of docs/CONFORMANCE-RPC-CONTRACT.md, between
the markers `<!-- rpc_contract: NAME begin -->` and `<!-- rpc_contract: NAME end -->`.

WHAT IT CHECKS. `--check`: both outputs are what a run would write, byte for byte; every success reply of the probe
record (contract.json `probe_record`) fits its handler's result type (no unknown field, no missing one, no wrong type);
every error reply's code is one the contract lists for that handler or the envelope's generic ones; a reply that is
not one JSON object is a mismatch unless a finding of contract.json names it. `--verify`: every citation resolves
inside its file at the pin (`git show <commit>:<path>` in the clone §1a names), and every literal error message (its leading
18 characters, the left one of a `/`-joined pair) lies within one line of its citation; a clone that is absent is SKIPPED BY NAME, never a pass:
the verdict line counts each clone's skipped citations, and with no clone at all it reads SKIPPED BY NAME, not GREEN.
The spec leg of tools/check.sh runs both `--check` and `--verify` (2026-10-15, lane wire-rpcleg).

Usage:
  tools/rpc_contract.py            write the interface and the page's sections
  tools/rpc_contract.py --check    exit 1 when an output is stale or the probe record disagrees with the contract
  tools/rpc_contract.py --verify   exit 1 when a citation does not hold at the pin
"""
