import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTRACT = os.path.join(ROOT, "corpus", "rpc", "contract.json")
RUST = os.path.join(ROOT, "harness", "src", "scenarios", "rpc_contract.rs")
